import type { Prisma, PrismaClient } from "../src/generated/prisma/client";

/**
 * Черновики первых рассылок (CRM → Рассылки). Создаются один раз по названию, тексты можно править в CRM.
 * Отправка возможна после подключения почтового канала (CRM → Интеграции → Почта): письма уходят только тем,
 * кто дал согласие на рассылку; {имя} и {ссылка} подставляются при отправке.
 */
export async function seedCampaigns(db: PrismaClient) {
  const drafts: { name: string; subject: string; text: string; segment: Record<string, unknown> }[] = [
    {
      name: "Запуск: первая коллекция T.Rodionova",
      subject: "Пять вещей, которые мы шили два года",
      segment: {},
      text: `{имя}, здравствуйте.

Сегодня открылся сайт T.Rodionova. В первой коллекции пять вещей: боди с открытыми плечами, брюки палаццо, юбка-трапеция с фирменной пряжкой, жакет с открытой спиной и платье с воротником-халтер. Всё чёрное, всё из натуральных волокон, всё сочетается между собой.

Каждая модель отшита тиражом до шестидесяти единиц. Распродаж не будет: цена не меняется до конца сезона.

Доставляем заказы через СДЭК, Яндекс Доставку и Яндекс Экспресс. Для возврата обратитесь в поддержку в течение 14 дней с момента получения.

Смотреть коллекцию: {ссылка}

С уважением,
Татьяна Родионова`,
    },
    {
      name: "Как выбрать размер (письмо 2)",
      subject: "Как выбрать свой размер",
      segment: { registeredDays: 10, maxLifetime: 1 },
      text: `{имя}, коротко о том, как мы решаем главную проблему покупки одежды онлайн — размер.

Сверьте свои мерки с таблицей размеров в карточке вещи.

Если сомневаетесь между размерами, мы написали короткую инструкцию с тремя мерками и подсказками по каждой модели: {ссылка}

Вопросы по посадке можно задать в чате на сайте: ответим в течение часа в рабочее время.`,
    },
    {
      name: "Избранное ждёт (письмо 3)",
      subject: "Вещи из вашего избранного ещё в наличии",
      segment: { wishlist: true, lastOrderMinDays: 14 },
      text: `{имя}, в вашем избранном лежат вещи, которые пока есть в наличии в вашем размере.

Напоминаем, что каждая модель отшита небольшим тиражом и не возвращается в продажу после того, как закончится. Если размер уйдёт, можно оставить заявку на поступление — мы напишем, когда вещь появится снова.

Посмотреть избранное: {ссылка}`,
    },
  ];
  let created = 0;
  for (const d of drafts) {
    if (await db.campaign.findFirst({ where: { name: d.name }, select: { id: true } })) continue;
    await db.campaign.create({ data: { name: d.name, channel: "EMAIL", status: "DRAFT", subject: d.subject, text: d.text, segment: d.segment as Prisma.InputJsonObject } });
    created++;
  }
  return created;
}
