import "server-only";
import { db } from "@/lib/db";
import { getSetting } from "@/lib/settings";
import { formatMoney } from "@/lib/money";

/**
 * Вопросы и ответы для покупательниц и для ИИ-ответов: ответ идёт первым предложением, факты берутся из настроек
 * (доставка, бренд, продавец) и справочника уровней Circle, чтобы на сайте не было двух разных цифр.
 */
export type Faq = { q: string; a: string; href?: string };

export async function siteFaq(): Promise<{ group: string; items: Faq[] }[]> {
  const [delivery, brand, seller, loyalty, tiers] = await Promise.all([
    getSetting("delivery"),
    getSetting("brand"),
    getSetting("seller"),
    getSetting("loyalty"),
    db.loyaltyTier.findMany({ orderBy: { threshold: "asc" } }),
  ]);
  const tierText = tiers.map((t) => `${t.name} — ${t.cashbackPct}% баллами${t.threshold ? ` при покупках от ${formatMoney(t.threshold)} за 12 месяцев` : " с первой покупки"}`).join("; ");
  const showroom = seller.showroom ? `Шоурум: ${seller.showroom}${seller.hours ? `, ${seller.hours}` : ""}.` : "Шоурума пока нет: вещи примеряют дома с курьером.";
  return [
    {
      group: "Доставка и примерка",
      items: [
        { q: "Сколько стоит доставка и когда она бесплатная?", a: `Доставка бесплатна при заказе от ${formatMoney(delivery.freeFrom)}. Курьер по Москве и Санкт-Петербургу — ${formatMoney(delivery.courier)}, 1–2 дня. СДЭК по России — ${formatMoney(delivery.cdek)}, 2–7 дней; Boxberry — ${formatMoney(delivery.boxberry)}.`, href: "/delivery" },
        { q: "Можно ли примерить вещи до оплаты?", a: "Да. В Москве и Санкт-Петербурге курьер привозит до 6 вещей и ждёт до 20 минут, пока вы примеряете; оплачиваете только то, что подошло. В другие города отправляем СДЭК с возможностью возврата.", href: "/delivery" },
        { q: "Где находится шоурум?", a: showroom, href: "/showroom" },
        { q: "Сколько ждать вещь по предзаказу?", a: "Предзаказ отшивается 4–6 недель; дата отгрузки указана в карточке вещи и в заказе. Тираж каждой модели — до 60 единиц, допошив только под предзаказ." },
      ],
    },
    {
      group: "Возврат и оплата",
      items: [
        { q: "Как вернуть вещь, если не подошла?", a: "Возврат принимается 14 дней с момента получения при сохранённых ярлыках и товарном виде: оформите его в личном кабинете, курьер заберёт вещь или отправьте СДЭК. Вещи по предзаказу и с подгонкой по размеру не возвращаются, брак меняем или возвращаем деньги в любой срок.", href: "/delivery" },
        { q: "Какие способы оплаты есть?", a: "Банковская карта, СБП, рассрочка банка-партнёра и оплата курьеру при получении. Чек приходит на e-mail. Часть суммы можно оплатить баллами Circle." },
        { q: "Бывают ли скидки и распродажи?", a: "Нет. Цена не меняется в течение сезона, распродаж не бывает: вещь стоит столько, сколько стоит. Выгода для постоянных покупательниц — баллы Circle и выкуп своих вещей обратно." },
      ],
    },
    {
      group: "Размеры и уход",
      items: [
        { q: "Как выбрать размер?", a: "Вещи шьются в размерах XS–L. Сравните свои мерки (грудь, талия, бёдра) с таблицей на странице «Размеры и мерки»; в карточке каждой вещи есть подсказка по посадке. Если сомневаетесь между двумя размерами, закажите оба на примерку курьером и оставьте один.", href: "/sizes" },
        { q: "Как ухаживать за вещами из шерсти и шёлка?", a: "Костюмная шерсть и жакеты — сухая чистка один-два раза в сезон, складки убирать паром, хранить на широких плечиках. Шёлк — только сухая чистка, без воды и солнца. Трикотаж из вискозы — деликатная стирка при 30° и сушка горизонтально. Подробные правила — на странице «Уход за изделиями».", href: "/care" },
        { q: "Из каких тканей и где сшиты вещи?", a: "Только натуральные волокна: шерсть, кашемир, шёлк, хлопок; синтетика до 2% и только для эластичности. Костюмная шерсть из Бьеллы, шёлк из Комо, кашемир из Монголии. Пошив в Португалии и Литве, контроль качества в Москве — каждая вещь проверяется вручную.", href: "/about" },
      ],
    },
    {
      group: "Circle и сервис",
      items: [
        { q: "Что такое T.Rodionova Circle и сколько баллов дают за регистрацию?", a: `Circle — программа лояльности: ${loyalty.welcomePoints.toLocaleString("ru-RU")} баллов за регистрацию, 1 балл = 1 ₽, ${loyalty.referralPoints.toLocaleString("ru-RU")} баллов за приглашённую подругу. Уровни: ${tierText}.`, href: "/circle" },
        { q: "Что такое pre-loved и выкуп вещей?", a: "Свою вещь T.Rodionova можно продать бренду обратно за баллы Circle, а на витрине pre-loved купить проверенные вещи прошлых сезонов с гарантией подлинности.", href: "/preloved" },
        { q: "Как связаться со службой заботы?", a: `Напишите в чат личного кабинета или на ${brand.email}, позвоните ${brand.phone}${brand.telegram ? ", напишите в Telegram" : ""}. ${seller.hours ? `Режим работы: ${seller.hours}.` : ""}`.trim(), href: "/account/support" },
      ],
    },
  ];
}

/**
 * Вопросы-ответы для карточки вещи: размер, уход, ткань и производство, доставка, возврат, цена и баллы, тираж.
 * Только факты об этой вещи и этой категории; общие вопросы — на /faq.
 */
export function productFaq(p: { name: string; care: string | null; composition: string | null; madeIn: string | null; price: number; isPreorder: boolean; isPreloved: boolean; condition?: string | null }, sizes: string[], delivery: { freeFrom: number; courier: number }, points: number): Faq[] {
  const items: Faq[] = [];
  if (sizes.length) items.push({ q: `В каких размерах есть ${p.name}?`, a: `${p.name} выпускается в размерах ${sizes.join(", ")}. Проверьте мерки по таблице размеров; в Москве и Санкт-Петербурге можно заказать два размера на примерку курьером и оставить один.`, href: "/sizes" });
  const madeIn = p.madeIn && !/^europe$/i.test(p.madeIn) ? p.madeIn : null;
  if (p.composition || madeIn) {
    items.push({ q: `Из чего и где сшита вещь ${p.name}?`, a: `${p.composition ? `Состав: ${p.composition}.` : ""} ${madeIn ? `Пошив: ${madeIn}; контроль качества в Москве, каждая вещь проверяется вручную.` : "Пошив в Португалии и Литве, контроль качества в Москве."}`.trim(), href: "/about#fabrics" });
  }
  if (p.care) items.push({ q: `Как ухаживать за вещью ${p.name}?`, a: p.care, href: "/care" });
  items.push({ q: `Как доставят ${p.name} и можно ли примерить?`, a: `Курьер по Москве и Санкт-Петербургу за 1–2 дня с примеркой до 20 минут (${formatMoney(delivery.courier)}, бесплатно от ${formatMoney(delivery.freeFrom)}), по России — СДЭК 2–7 дней.${p.isPreorder ? " Вещь по предзаказу отшивается 4–6 недель." : ""}`, href: "/delivery#fitting" });
  items.push({ q: `Можно ли вернуть ${p.name}?`, a: p.isPreorder ? "Вещь по предзаказу возврату по размеру не подлежит; брак меняем или возвращаем деньги в любой срок." : "Да, 14 дней с момента получения при сохранённых ярлыках и товарном виде: возврат оформляется в личном кабинете, обратная доставка за счёт покупательницы, для уровня Privé — бесплатно.", href: "/delivery#returns" });
  items.push({
    q: `Сколько стоит ${p.name} и сколько баллов начислят?`,
    a: p.isPreloved
      ? `${formatMoney(p.price)}. Вещь pre-loved проверена ателье${p.condition ? `, состояние: ${p.condition}` : ""}; подлинность гарантирована. За покупку начислят ${points.toLocaleString("ru-RU")} баллов Circle (1 балл = 1 ₽).`
      : `${formatMoney(p.price)}; цена не меняется в течение сезона, распродаж не бывает. За покупку начислят ${points.toLocaleString("ru-RU")} баллов Circle (1 балл = 1 ₽), доставка бесплатна от ${formatMoney(delivery.freeFrom)}.`,
    href: "/circle",
  });
  if (!p.isPreloved) items.push({ q: `Сколько единиц ${p.name} выпущено и будет ли допошив?`, a: "Тираж каждой модели T.Rodionova — до 60 единиц, допошив только под предзаказ. Если вашего размера нет в наличии, подпишитесь на уведомление о поступлении в карточке вещи.", href: "/about#rules" });
  return items;
}
