import "server-only";
import { getSetting } from "@/lib/settings";
import { publicPhone } from "@/lib/seo";

/**
 * Вопросы и ответы для покупательниц и для ИИ-ответов: ответ идёт первым предложением, факты берутся из настроек
 * (доставка, бренд, продавец), чтобы на сайте не было двух разных цифр.
 */
export type Faq = { q: string; a: string; href?: string };

export async function siteFaq(): Promise<{ group: string; items: Faq[] }[]> {
  const [brand, seller] = await Promise.all([
    getSetting("brand"),
    getSetting("seller"),
  ]);
  const showroom = seller.showroom ? `Шоурум: ${seller.showroom}${seller.hours ? `, ${seller.hours}` : ""}.` : "Сейчас заказы принимаются онлайн.";
  return [
    {
      group: "Доставка",
      items: [
        { q: "Как доставляют заказы?", a: "Через СДЭК, Яндекс Доставку и Яндекс Экспресс.", href: "/delivery" },
        { q: "Где находится шоурум?", a: showroom, href: "/showroom" },
      ],
    },
    {
      group: "Возврат и цены",
      items: [
        { q: "Как оформить возврат?", a: "Обратитесь в поддержку в течение 14 дней после получения заказа. Сохраните ярлыки и товарный вид вещи.", href: "/delivery#returns" },
        { q: "Бывают ли скидки и распродажи?", a: "Нет. Цена не меняется в течение сезона, распродаж не бывает: вещь стоит столько, сколько стоит." },
      ],
    },
    {
      group: "Размеры и уход",
      items: [
        { q: "Как выбрать размер?", a: "Вещи шьются в размерах XS–L. Сравните свои мерки (грудь, талия, бёдра) с таблицей на странице «Размеры и мерки»; в карточке каждой вещи есть подсказка по посадке.", href: "/sizes" },
        { q: "Как ухаживать за вещами из шерсти и шёлка?", a: "Костюмная шерсть и жакеты — сухая чистка один-два раза в сезон, складки убирать паром, хранить на широких плечиках. Шёлк — только сухая чистка, без воды и солнца. Трикотаж из вискозы — деликатная стирка при 30° и сушка горизонтально. Подробные правила — на странице «Уход за изделиями».", href: "/care" },
        { q: "Из каких тканей и где сшиты вещи?", a: "Основа — натуральные волокна: шерсть, кашемир, шёлк, хлопок. Вискозу, эластан, полиамид или полиэстер добавляем, только когда они нужны вещи для посадки, тянучести или формы; точный состав — в карточке каждой вещи. Костюмная шерсть из Бьеллы, шёлк из Комо, кашемир из Монголии. Пошив в Португалии и Литве, контроль качества в Москве — каждая вещь проверяется вручную.", href: "/about" },
      ],
    },
    {
      group: "Сервис",
      items: [
        { q: "Как связаться со службой заботы?", a: `Напишите в чат личного кабинета или на ${brand.email}${publicPhone(brand.phone) ? `, позвоните ${publicPhone(brand.phone)}` : ""}${brand.telegram ? ", напишите в Telegram" : ""}. ${seller.hours ? `Режим работы: ${seller.hours}.` : ""}`.trim(), href: "/account/support" },
      ],
    },
  ];
}
